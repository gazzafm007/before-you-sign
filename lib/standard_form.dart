Notes – Termination of agreement
1. You may terminate this agreement by giving us at least 30 days’ written notice, and may move your home off the
    residential site at any time after giving us that written notice, in accordance with the Act.
2. We may only terminate this agreement in one or more of the following circumstances and in accordance with
    the Act:
      (a) if you seriously or persistently breach this site agreement,
      (b) if we require vacant possession of the residential site in order to comply with an obligation imposed by
           or under legislation to carry out works (including works in the nature of repairs or upgrading) within the
           residential site or community,
      (c) if the community is to be closed,
      (d) if there is to be a change in the use of the residential site,
      (e) if the residential site is appropriated or acquired under legislation of the State or Commonwealth by
           compulsory process authorised by that legislation,
      (f) if the site is not lawfully useable for the purposes of a residential site,
      (g) for serious misconduct, following an application to the Tribunal.
